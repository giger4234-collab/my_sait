const {chromium}=require("C:/Users/Artemon/AppData/Local/Temp/orbita-qa-tools-20261109/node_modules/playwright-core");
const fs=require("node:fs");
const assert=require("node:assert/strict");
(async()=>{
  const base="http://127.0.0.1:3001/my_sait/";
  const errors=[],bad=[];
  const redirect=await fetch(base.slice(0,-1),{redirect:"manual"});
  assert.equal(redirect.status,308);
  assert.equal(redirect.headers.get("location"),"/my_sait/");
  const browser=await chromium.launch({channel:"chrome",headless:true});
  const page=await browser.newPage({viewport:{width:1366,height:900},reducedMotion:"no-preference"});
  page.on("pageerror",e=>errors.push(e.message));
  page.on("response",r=>{if(r.url().startsWith(base)&&r.status()>=400)bad.push({url:r.url(),status:r.status()})});
  await page.goto(base,{waitUntil:"networkidle"});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>document.querySelector('[data-variant="field"]')?.dataset.ready==="true");
  await page.locator('[data-variant="field"]').getByRole("button",{name:"Пауза анимации",exact:true}).click();
  await page.screenshot({path:"D:/Projects/my_sait/.impeccable/review/github-pages-prefix-desktop.png"});
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute("href"),"https://example-user.github.io/my_sait/");
  assert((await page.locator('meta[property="og:image"]').getAttribute("content")).includes("/my_sait/assets/images/"));
  await page.locator("#solar-system").getByRole("button",{name:/Марс/}).click();
  const image=page.locator("[data-planet=mars] img");
  await image.evaluate(i=>i.decode());
  assert.equal(await image.getAttribute("src"),"/my_sait/assets/textures/mars.webp");
  assert.equal(await image.evaluate(i=>i.naturalWidth>0),true);
  await page.getByRole("button",{name:"Открыть меню",exact:true}).click();
  await page.locator("#site-nav").getByRole("link",{name:"Контакт"}).click();
  assert.equal(new URL(page.url()).pathname,"/my_sait/");
  assert.equal(await page.locator("#site-nav").isVisible(),false);
  assert.equal(errors.length,0,JSON.stringify(errors));assert.equal(bad.length,0,JSON.stringify(bad));
  const report={base,redirect:308,webgl:true,canonical:true,planetTextures:true,menuAndAnchors:true,pageErrors:errors,failedRequests:bad};
  fs.writeFileSync("D:/Projects/my_sait/.impeccable/review/github-pages-qa.json",JSON.stringify(report,null,2));
  await browser.close();
  console.log("PASS: /my_sait/ HTML, styles, fonts, live WebGL chunks, planet images, menu, anchors, redirect and canonical metadata.");
})().catch(e=>{console.error(e);process.exit(1)});
